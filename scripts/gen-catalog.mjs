#!/usr/bin/env node
// Regenerates the skill catalog table in README.md between the catalog markers.
// Usage: node scripts/gen-catalog.mjs           (rewrite README.md)
//        node scripts/gen-catalog.mjs --check   (exit 1 if README.md is out of date)
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { REPO_ROOT, loadSkills, isInternal, parseCompatibility } from "./lib/skills.mjs";

const README = join(REPO_ROOT, "README.md");
const START = "<!-- catalog:start (generated by scripts/gen-catalog.mjs; do not edit by hand) -->";
const END = "<!-- catalog:end -->";

const cell = (s) => String(s).replace(/\s+/g, " ").trim().replace(/\|/g, "\\|");

const skills = (await loadSkills()).filter((s) => !s.error && !isInternal(s));
const rows = skills.map((s) => {
  const compat = (parseCompatibility(s.data.metadata?.compatibility) ?? []).join(", ");
  return `| [\`${s.data.name}\`](skills/${s.folder}/SKILL.md) | ${cell(s.data.description)} | ${cell(compat)} |`;
});
const table = [
  "| Skill | Description | Compatibility |",
  "|---|---|---|",
  ...(rows.length ? rows : ["| _none yet_ | | |"]),
].join("\n");

const current = await readFile(README, "utf8");
const startIdx = current.indexOf(START);
const endIdx = current.indexOf(END);
if (startIdx < 0 || endIdx < startIdx) {
  console.error(`README.md is missing the catalog markers:\n${START}\n${END}`);
  process.exit(1);
}
const next = current.slice(0, startIdx + START.length) + "\n" + table + "\n" + current.slice(endIdx);

if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("README.md catalog is out of date. Run: npm run catalog");
    process.exit(1);
  }
  console.log("✓ README.md catalog is up to date");
} else if (next !== current) {
  await writeFile(README, next);
  console.log(`Updated README.md catalog (${rows.length} skill(s))`);
} else {
  console.log("README.md catalog already up to date");
}
