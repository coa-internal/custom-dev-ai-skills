#!/usr/bin/env node
// Writes (or checks) the City standards digest in a repository's AGENTS.md.
//
// The digest is one line per rule, generated from this skill's references/*.md, so AI tools see
// every rule ID and level in each session without loading the full standards.
//
// Usage, from the repository root:
//   node .agents/skills/dev-standards/scripts/agents-digest.mjs           write or update the digest
//   node .agents/skills/dev-standards/scripts/agents-digest.mjs --check   exit 1 if missing or stale
//   node .agents/skills/dev-standards/scripts/agents-digest.mjs --print   print the digest only
//   Add --file <path> to target a file other than ./AGENTS.md.
//
// No dependencies. Node.js >= 22.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import console from 'node:console';
import process from 'node:process';

const SKILL_NAME = 'dev-standards';
const REFERENCES_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'references');
const START = `<!-- ${SKILL_NAME}:start -->`;
const END = `<!-- ${SKILL_NAME}:end -->`;
const IGNORE_START = '<!-- prettier-ignore-start -->';
const IGNORE_END = '<!-- prettier-ignore-end -->';
const RULE_RE = /^###\s+([A-Z][A-Z0-9]*-\d{3})\s+\((MUST|SHOULD)\)\s+(.+?)\s*$/;
const TITLE_RE = /^#\s+(.+?)\s*$/;

function parseArgs(argv) {
	const args = { check: false, print: false, file: 'AGENTS.md' };
	for (let i = 0; i < argv.length; i++) {
		const arg = argv[i];
		if (arg === '--check') args.check = true;
		else if (arg === '--print') args.print = true;
		else if (arg === '--file') args.file = argv[++i];
		else throw new Error(`Unknown argument: ${arg}`);
	}
	if (!args.file) throw new Error('--file needs a path');
	return args;
}

/** Reads every references/*.md file and returns its title and rules, in file name order. */
async function loadStandards() {
	const names = (await readdir(REFERENCES_DIR)).filter((n) => n.endsWith('.md')).sort();
	const seen = new Map();
	const standards = [];
	for (const name of names) {
		const text = (await readFile(join(REFERENCES_DIR, name), 'utf8')).replace(/\r\n/g, '\n');
		const lines = text.split('\n');
		const title = lines.map((l) => TITLE_RE.exec(l)).find(Boolean)?.[1] ?? name;
		const rules = [];
		for (const line of lines) {
			const m = RULE_RE.exec(line);
			if (!m) continue;
			const [, id, level, summary] = m;
			if (seen.has(id)) throw new Error(`Duplicate rule ID ${id} in ${name} and ${seen.get(id)}`);
			seen.set(id, name);
			rules.push({ id, level, summary });
		}
		if (rules.length > 0) standards.push({ file: name, title, rules });
	}
	if (standards.length === 0) throw new Error(`No rules found in ${REFERENCES_DIR}`);
	return standards;
}

/** Returns the pinned ref of this skill from ./skills-lock.json, or null if not found. */
async function pinnedVersion() {
	try {
		const lock = JSON.parse(await readFile('skills-lock.json', 'utf8'));
		return lock?.skills?.[SKILL_NAME]?.ref ?? null;
	} catch {
		return null;
	}
}

function renderDigest(standards, version) {
	const from = version ? `${SKILL_NAME} ${version}` : `the ${SKILL_NAME} skill`;
	const out = [
		`<!-- Generated by ${SKILL_NAME}/scripts/agents-digest.mjs from ${from}. Do not edit by hand; re-run the script after upgrading the skill. -->`,
		'',
		'## City development standards',
		'',
		`These rules come from ${from}. **MUST** rules apply unless this repository records an approved waiver. **SHOULD** rules are City defaults; a deviation is recorded in a project ADR that cites the rule ID. Before acting on a rule, read its full text in the \`${SKILL_NAME}\` skill's \`references/\` folder.`,
	];
	for (const { file, title, rules } of standards) {
		out.push('', `### ${title} (\`references/${file}\`)`, '');
		for (const { id, level, summary } of rules) out.push(`- **${id}** (${level}) ${summary}`);
	}
	return out.join('\n');
}

function wrapBlock(digest) {
	return [IGNORE_START, START, digest, END, IGNORE_END].join('\n');
}

/** Returns the file text with the digest inserted or replaced, or null if markers are malformed. */
function applyDigest(text, digest) {
	const start = text.indexOf(START);
	const end = text.indexOf(END);
	if (start === -1 && end === -1) {
		const sep = text.length === 0 ? '' : text.endsWith('\n') ? '\n' : '\n\n';
		return `${text}${sep}${wrapBlock(digest)}\n`;
	}
	if (start === -1 || end === -1 || end < start) return null;
	return `${text.slice(0, start + START.length)}\n${digest}\n${text.slice(end)}`;
}

async function main() {
	const args = parseArgs(process.argv.slice(2));
	const digest = renderDigest(await loadStandards(), await pinnedVersion());

	if (args.print) {
		console.log(wrapBlock(digest));
		return;
	}

	let current = '';
	try {
		current = (await readFile(args.file, 'utf8')).replace(/\r\n/g, '\n');
	} catch (err) {
		if (err.code !== 'ENOENT') throw err;
	}
	const next = applyDigest(current, digest);
	if (next === null) {
		console.error(`${args.file}: found only one of ${START} / ${END}. Fix the markers by hand.`);
		process.exit(1);
	}

	if (args.check) {
		if (next !== current) {
			console.error(
				`${args.file}: the ${SKILL_NAME} digest is missing or out of date. Run: node .agents/skills/${SKILL_NAME}/scripts/agents-digest.mjs`,
			);
			process.exit(1);
		}
		console.log(`${args.file}: ${SKILL_NAME} digest is up to date.`);
		return;
	}

	if (next === current) {
		console.log(`${args.file}: ${SKILL_NAME} digest already up to date.`);
		return;
	}
	await writeFile(args.file, next);
	console.log(`${args.file}: wrote the ${SKILL_NAME} digest. Review and commit the change.`);
}

main().catch((err) => {
	console.error(err.message);
	process.exit(1);
});
